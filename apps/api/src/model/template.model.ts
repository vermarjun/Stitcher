import {Schema, Document, Model, model, Types} from "mongoose";

export enum TemplateType {
  VIDEO = 'video',
  AUDIO = 'audio',
}

export interface ITemplate extends Document {
    // title of the post, scene_name is the name of the scene hence big difference!
    title: string; //changed this earlier this was name
    post_description?: string; // changed this aswell earlier this was just description
    type: TemplateType;
    thumbnail?: string; 
    url: string; 
    duration?: number;
    bytes: number;
    metadata: Record<string, any>;
    scene_name?: string; //scene name
    scene_description?: string; //just the description given to the AI agent => prompt generated by the planner
    code?: string; // added new
    // Virtual fields for frontend
    likesCount?: number;
    isLikedByUser?: boolean;
    isInProject?: boolean;  // New field to show if template is already in current project
    projectAssetId?: string; // ID of the asset if already in project (for easy removal)
}

const TemplateSchema = new Schema<ITemplate>({
    title: { 
        type: String, 
        required: true,
        unique: true,
    },
    post_description: { 
        type: String,
    },
    type: { 
        type: String, 
        enum: Object.values(TemplateType), 
        required: true,
    },
    thumbnail: { 
        type: String, 
        required: true,
        default: ""
    },
    url: { 
        type: String, 
        required: true 
    },
    duration: { 
        type: Number,
        min: 0
    },
    bytes: { 
        type: Number, 
        default: 0,
        min: 0
    },
    metadata: { 
        type: Schema.Types.Mixed, 
        default: {} 
    },
    scene_name: {
        type: Schema.Types.String,
        default: ""
    },
    scene_description: {
        type: Schema.Types.String,
        default: ""
    },
    code: {
        type: Schema.Types.String,
        default: ""
    }
}, { 
    timestamps: true,
    toJSON: { virtuals: true },
    toObject: { virtuals: true }
});

// Virtual for likes count (will be populated via aggregation)
TemplateSchema.virtual('likesCount', {
    ref: 'TemplateLike',
    localField: '_id',
    foreignField: 'templateId',
    count: true
});

const Template: Model<ITemplate> = model<ITemplate>('Template', TemplateSchema);
export default Template;
